// Runs the VORG Strategy Generator v1.1 against current repo inputs and writes the
// engine-generated plan artifact to research/market-positioning/.
// Usage: node run-strategy-generator.mjs   (compile positioning + strategy first)
import vm from 'node:vm';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const source = readFileSync(join(here, 'strategy-generator.js'), 'utf8');
const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(source, sandbox, { filename: 'strategy-generator.js' });
const engine = sandbox.VorgStrategyGenerator;

const positioningSource = readFileSync(join(here, 'market-positioning-prediction.js'), 'utf8');
vm.runInContext(positioningSource, sandbox, { filename: 'market-positioning-prediction.js' });
const positioningEngine = sandbox.VorgMarketPositioning;

const libraryPack = JSON.parse(
  readFileSync(join(root, 'research/market-positioning/strategy-mechanism-library-2026-08-22.json'), 'utf8')
);
const skuInventory = JSON.parse(readFileSync(join(root, 'research/market-positioning/sku-inventory.json'), 'utf8'));
const gatesPack = JSON.parse(readFileSync(join(root, 'research/market-positioning/route-to-market-gates.json'), 'utf8'));
const candidatesPack = JSON.parse(readFileSync(join(root, 'research/market-positioning/candidates.json'), 'utf8'));
const sourceLedger = JSON.parse(readFileSync(join(root, 'research/market-positioning/source-ledger.json'), 'utf8'));
const mechanismPack = JSON.parse(readFileSync(join(root, 'research/market-positioning/mechanism-cards.json'), 'utf8'));

const marketRecommendation = positioningEngine.recommendPosition({
  generatedAt: '2026-08-22T20:00:00.000Z',
  candidates: candidatesPack.candidates,
  sources: sourceLedger.sources,
  signals: sourceLedger.signals,
  mechanisms: mechanismPack.cards,
  gates: gatesPack.gates,
  receipts: []
});
const candidateById = new Map(candidatesPack.candidates.map((candidate) => [candidate.id, candidate]));
const orderedMarkets = marketRecommendation.rankedCandidates
  .map((result, index) => {
    const candidate = candidateById.get(result.candidateId);
    return candidate
      ? { id: candidate.id, metro: candidate.metro, country: candidate.country, rank: index + 1, selectionRole: result.selectionRole }
      : null;
  })
  .filter(Boolean);

const TEST_CASH_POOL_CAD = 500; // working assumption — founder-configurable, separate from production ceiling

const input = {
  generatedAt: '2026-08-22T21:00:00.000Z',
  brand: {
    name: 'VORG-EAVY',
    industry: 'fashion',
    skus: skuInventory.skus.map((s) => ({
      id: s.id,
      name: s.name,
      role: s.role,
      workingUnits: s.workingUnits,
      workingPriceCad: s.workingPriceCad,
      proofStatus: s.proofStatus
    })),
    productionCeilingCad: skuInventory.productionCeilingCad,
    operatingMarket: 'Canada',
    sellThroughGoalPct: 85,
    testCashPoolCad: TEST_CASH_POOL_CAD
  },
  library: libraryPack.cards,
  markets: orderedMarkets,
  gates: gatesPack.gates.map((g) => ({
    id: g.id,
    label: g.label,
    state: g.state,
    hardStop: g.hardStop,
    region: g.region,
    appliesToMarkets: g.appliesToMarkets,
    notes: g.notes
  }))
};

const result = engine.generateStrategy(input);
if (!result.winner || !result.plan) {
  console.error('Engine refused to pick a winner — check library/gates inputs.');
  process.exit(1);
}

const w = result.winner;
const plan = result.plan;
const lines = [];
const push = (s = '') => lines.push(s);

push('# VORG Drop 001 — Generated Strategy Plan (2026-08-22)');
push('');
push('**ENGINE-GENERATED FORECAST PLAN — receipts pending.**');
push('');
push(`Generated by \`${result.version}\` at ${result.generatedAt} from public-prior evidence cards with **zero first-party sales input**. This is a prediction-engine play, not demand proof. It does not authorize production spend or Drop OS GO.`);
push('');
push('Regenerate: `cd site && npx tsc -p tsconfig.strategy-generator.json && node run-strategy-generator.mjs`');
push('');
push('## 1. What decision does this support?');
push('');
push('Which go-to-market strategy VORG-EAVY runs for Drop 001 and the staged plan for running it — selected and compiled by the strategy generator, to be recalibrated with first-party receipts toward the pre-existing 85% sell-through goal.');
push('');
push('## 2. Winner (engine-selected)');
push('');
push(`**${w.label}** (\`${w.strategyId}\`) — total score ${w.totalScore} (evidence ${w.evidenceScore} x preparedness ${w.preparedness} x goal-fit ${w.goalFit}).`);
push('');
push(`Runner-up: **${result.runnerUp.label}** (\`${result.runnerUp.strategyId}\`) — score ${result.runnerUp.totalScore}.`);
push('');
push(`Strategy ranking strength: **${result.rankingStrength}**. Co-winner threshold: **${result.winnerSetThresholdPoints} points**. Co-winner set: ${result.winnerSet.map((candidate) => candidate.label).join(' + ')}.`);
push('');
push(`Market lead: **${marketRecommendation.provisionalWinner?.metro || 'none'}**. Market ranking strength: **${marketRecommendation.rankingStrength}**. Co-finalist set: ${marketRecommendation.provisionalWinners.map((candidate) => candidate.metro).join(', ') || 'none'}.`);
push('');
push('Why the engine picked it:');
push('');
for (const r of w.reasons) push(`- ${r}`);
push('');
push('### Full ranking');
push('');
push('| Strategy | Evidence | Preparedness | Goal fit | Total |');
push('|---|---|---|---|---|');
for (const s of result.rankedStrategies) {
  push(`| ${s.label} | ${s.evidenceScore} | ${s.preparedness} | ${s.goalFit} | **${s.totalScore}** |`);
}
push('');
push('### Stress test — public-prior evidence behind the winner');
push('');
push('Supporting (worked elsewhere, with transferability discount where cross-industry):');
push('');
for (const u of w.stress.supporting) {
  push(`- **${u.reference}** (${u.industry}${u.crossIndustry ? `, cross-industry x${u.transferFactor}` : ''}, weight ${u.weight}): ${u.why}${u.tweakNote ? ` _Tweak: ${u.tweakNote}_` : ''}`);
}
push('');
push('Contradicting (failed/mixed elsewhere — lowers the score with reasons, does not disqualify):');
push('');
for (const u of w.stress.contradicting) {
  push(`- **${u.reference}** (${u.industry}, weight ${u.weight}): ${u.why}`);
}
push('');
push(`Unpreparedness audit — what breaks first: ${w.stress.unpreparedness.breaksFirst}`);
push('');
push('## 3. The generated plan');
push('');
push(`- Wedge metro (from positioning engine ranking, forecast only): **${plan.wedgeMetro}**`);
push(`- Sell-through goal: **${plan.goalSellThroughPct}%**`);
push(`- Test cash pool: **C$${plan.testCashPoolCad}** (working assumption, founder-configurable) — allocated C$${plan.budgetAllocatedCad}`);
push(`- Production ceiling: C$${plan.productionCeilingCad.min}-C$${plan.productionCeilingCad.max} — **untouched by this plan**`);
push(`- Cash policy: ${plan.cashPolicy}`);
push('');
for (const phase of plan.phases) {
  push(`### ${phase.id} — ${phase.label}`);
  push('');
  push(`_${phase.objective}_`);
  push('');
  for (const waveId of phase.waveIds) {
    const wave = plan.waves.find((x) => x.id === waveId);
    push(`**${wave.label}** (\`${wave.id}\`, mechanism \`${wave.mechanism}\`) — status: ${wave.status.toUpperCase()}, budget cap C$${wave.budgetCapCad}${wave.frozenReason ? ` — ${wave.frozenReason}` : ''}`);
    push('');
    for (const item of wave.items) {
      push(`- ${item.action}`);
      push(`  - Owner: ${item.ownerRole} | Budget cap: C$${item.budgetCapCad} | Evidence: ${item.evidenceLabel}${item.evidenceCardIds.length ? ` (${item.evidenceCardIds.join(', ')})` : ''}`);
      push(`  - Measure: ${item.measurement.metric} | Success: ${item.measurement.successThreshold}`);
      push(`  - Kill rule: ${item.measurement.killRule}`);
      if (item.gateDependencies.length) push(`  - Gate dependencies: ${item.gateDependencies.join(', ')}`);
    }
    push('');
  }
}
push('## 4. Reversal conditions');
push('');
for (const r of result.reversalConditions) push(`- ${r}`);
push('');
push('## 5. Unpreparedness report (open gates)');
push('');
push('| Gate | State | Hard stop | Consequence |');
push('|---|---|---|---|');
for (const g of result.unpreparednessReport) {
  push(`| ${g.label} | ${g.state} | ${g.hardStop ? 'yes' : 'no'} | ${g.consequence} |`);
}
push('');
push('## 6. Known / Priors / Assumptions / Unresolved');
push('');
push('### Known (facts)');
push('');
push('- Five active SKUs (Firm Jacket, women\u2019s low-rise denim, men\u2019s denim, scarf, women\u2019s top/bodysuit), all unquoted/unsampled (`research/market-positioning/sku-inventory.json`).');
push('- Production ceiling C$5,000-C$6,000 unless the founder revises it.');
push(`- ${result.unpreparednessReport.filter((g) => g.hardStop).length} hard-stop gates are open right now; every affected plan branch above is frozen.`);
push('- Zero first-party VORG sales receipts exist; this plan is built entirely from public-prior evidence cards.');
push('');
push('### Priors (external evidence cards)');
push('');
push(`- ${libraryPack.cards.length} evidence cards in \`research/market-positioning/strategy-mechanism-library-2026-08-22.json\`, each with sourceUrl + dateChecked + workedOrFailed + why + transferability conditions.`);
push(`- Winner is backed by ${w.stress.supporting.length} supporting and lowered by ${w.stress.contradicting.length} contradicting public-prior cards (failure evidence is input, not disqualification).`);
push('- Cross-industry receipts (sneaker raffles, restaurant scarcity, beauty community, gaming undersupply, artist collabs, festival hype-collapse) carry explicit transferability discounts and tweak notes.');
push('');
push('### Assumptions (working, engine-declared)');
push('');
for (const a of result.assumptions) push(`- ${a}`);
push('');
push('### Unresolved');
push('');
push('- Founder has not confirmed the C$500 test cash pool figure — budgets rescale automatically when it changes.');
push('- Every open hard-stop gate above is unresolved by definition; the drop-window branch stays frozen until all clear with evidence.');
push('- Wedge metro remains a forecast (positioning engine, forecast-only status); Ottawa/Gatineau stays the Canadian fallback.');
push('- No creator briefs signed, no waitlist live, no venue package — all plan lines are pre-receipt.');
push('');
push('## 7. How first-party results plug in');
push('');
push('Supply `firstPartyResults` (sessions, purchases, sellThroughBySku, waveOutcomes with receipt URLs) to `generateStrategy(...)`. The engine then: recomputes the posterior strategy score, kills failing waves and reallocates their budget to passing ones (never exceeding the pool), tracks distance to the 85% goal overall and per SKU, and emits a full audit trail (prior \u2192 evidence \u2192 posterior \u2192 change \u2192 why). Deterministic given the same inputs. Contract: `strategy/strategy-generator-v1.md`.');
push('');

const outPath = join(root, 'research/market-positioning/generated-strategy-plan-2026-08-22.md');
writeFileSync(outPath, lines.join('\n'), 'utf8');
writeFileSync(
  join(here, 'strategy-runtime.js'),
  `window.VORG_STRATEGY_RUNTIME = ${JSON.stringify({
    generatedBy: result.version,
    marketRecommendation: {
      version: marketRecommendation.version,
      rankingStrength: marketRecommendation.rankingStrength,
      provisionalWinner: marketRecommendation.provisionalWinner,
      provisionalWinners: marketRecommendation.provisionalWinners
    },
    result
  }, null, 2)};\n`,
  'utf8'
);
console.log(`Wrote ${outPath}`);
console.log(`Winner: ${w.strategyId} (${w.totalScore}); runner-up: ${result.runnerUp.strategyId} (${result.runnerUp.totalScore})`);
console.log(`Waves: ${plan.waves.length}; budget allocated C$${plan.budgetAllocatedCad} of C$${plan.testCashPoolCad}`);
